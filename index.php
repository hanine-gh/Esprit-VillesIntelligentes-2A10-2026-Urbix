<?php
declare(strict_types=1);

// =====================================
// SESSION : configuration sécurisée (les ini_set doivent précéder session_start)
// =====================================
ini_set('session.use_strict_mode', '1');   // reject session IDs that were not generated by the server
ini_set('session.cookie_httponly', '1');   // make the cookie inaccessible to JavaScript to protect against XSS attacks
ini_set('session.cookie_samesite', 'Lax'); // limit CSRF attacks by restricting third-party cookies
// ini_set('session.cookie_secure', '1');  // à décommenter si le site est servi en HTTPS
session_start();

// =====================================
// SESSION : expiration après inactivité
// =====================================
const SESSION_TIMEOUT = 1800; // 30 minutes

if (isset($_SESSION['user_id'], $_SESSION['last_activity'])
    && (time() - (int) $_SESSION['last_activity']) > SESSION_TIMEOUT) {
    $_SESSION = [];
    session_destroy();
    header('Location: index.php?page=login&expired=1');
    exit;
}
if (isset($_SESSION['user_id'])) {
    $_SESSION['last_activity'] = time();
}

// =====================================
// HTTP security headers
// =====================================
header('X-Frame-Options: DENY');                            // anti clickjacking
header('X-Content-Type-Options: nosniff');                  // prevents MIME-sniffing
header('Referrer-Policy: strict-origin-when-cross-origin');
// limits XSS : seules les ressources du site sont acceptées
// (+ Google Fonts, utilisé par le template dans main.css)
header("Content-Security-Policy: default-src 'self'; "
    . "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; "
    . "font-src 'self' https://fonts.gstatic.com; "
    . "img-src 'self' data:");

// =====================================
// CHARGEMENT DE L'APPLICATION
// =====================================
require_once __DIR__ . '/config.php';
require_once __DIR__ . '/app/helpers.php';

spl_autoload_register(function (string $class) {
    $path = __DIR__ . '/app/' . str_replace(['App\\', '\\'], ['', '/'], $class) . '.php';
    if (is_file($path)) {
        require $path;
    }
});

// =====================================
// ROUTAGE : index.php?page=...
// =====================================
$routes = require __DIR__ . '/app/routes.php';
$page   = $_GET['page'] ?? 'home';

if (!is_string($page) || !isset($routes[$page])) {
    http_response_code(404);
    exit('Page introuvable');
}

[$class, $method] = $routes[$page];
(new $class)->$method();
